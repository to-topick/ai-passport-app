INSTRUCTIONS = "誠実に、聞き手に語りかけるように、温かみのある口調で話してください。"


def generate(filename: str, text: str) -> None:
    output_path = OUTPUT_DIR / filename
    if output_path.exists():
        print(f"[SKIP] {filename} はすでに存在します")
        return

    print(f"[生成中] {filename} ...")
    response = client.audio.speech.create(
        model="gpt-4o-mini-tts",
        voice="nova",
        input=text,
        instructions=INSTRUCTIONS,
    )
    response.stream_to_file(output_path)
    print(f"[完了]  {filename} → {output_path}")


if __name__ == "__main__":
    for fname, script in SCRIPTS.items():
        generate(fname, script)
    print("\nすべての音声ファイルの生成が完了しました。")
